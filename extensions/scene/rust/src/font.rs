/// The glyph for `c`: its 7 rows.
pub fn glyph(c: char) -> [&'static str; 7] {
    let c = match c {
        '\u{2032}' => '\'',
        c => c.to_ascii_uppercase(),
    };
    GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .or_else(|| GLYPHS.iter().find(|(g, _)| *g == '?'))
        .map(|(_, rows)| *rows)
        .unwrap_or([""; 7])
}

/// The pixels of `text` set by the font: (column, row) in glyph pixels
/// from the text's top left, each glyph 5 wide with one blank between.
pub fn pixels(text: &str) -> Vec<(usize, usize)> {
    let mut out = Vec::new();
    for (k, c) in text.chars().enumerate() {
        for (row, line) in glyph(c).iter().enumerate() {
            for (col, b) in line.bytes().enumerate() {
                if b == b'#' {
                    out.push((6 * k + col, row));
                }
            }
        }
    }
    out
}
